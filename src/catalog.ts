import type { Level, Scenario } from './engine/model.ts'

// Примеры взяты из опубликованных разборов, не выдуманы.
// Новичок и джун: MDN «Handling conflicts», MDN Specificity, MDN CSS FAQ, web.dev/learn/css/specificity.
// Мидл: MDN !important, CSS-Tricks про :is/:where и порядок, web.dev «:is() and :where()».
// Синьор и собес: MDN Cascade introduction, MDN Cascade layers, MDN «Test your skills: The Cascade»,
// Manuel Matuzović «using !important in cascade layers», Chrome «Cascade layers are coming».

function ex(
  id: string,
  n: number,
  title: string,
  level: Level,
  html: string,
  css: string,
  target: string,
  properties: string[] = ['color'],
): Scenario {
  return {
    id,
    title: `${String(n).padStart(2, '0')} · ${title}`,
    level,
    html: html.endsWith('\n') ? html : `${html}\n`,
    css: css.endsWith('\n') ? css : `${css}\n`,
    target,
    properties,
  }
}

